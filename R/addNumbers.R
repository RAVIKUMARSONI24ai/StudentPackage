#' Add two numbers
#'
#' Takes two numeric inputs and returns their sum.
#'
#' @param a First number (numeric).
#' @param b Second number (numeric).
#' @return The sum of a and b (numeric).
#' @export
#' @examples
#' addNumbers(10, 20)
#' addNumbers(2, 3)
addNumbers <- function(a, b) {
  return(a + b)
}
